/** Somente leitura: por que a rotina não está enviando candidaturas?  --email=conta */
import { readFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { Firestore } from "@google-cloud/firestore";
import { GoogleAuth, OAuth2Client } from "google-auth-library";
import { firestoreStore } from "../server/storage-firestore";
import { and, eq } from "../server/storage-types";
import { analyze, matchesObjectiveFilters, matchesSelectedSites } from "../server/engine";

const email = process.argv.find((a) => a.startsWith("--email="))?.slice(8);
if (!email) throw new Error("Informe --email=conta");
const config = JSON.parse(await readFile(join(homedir(), ".config/configstore/firebase-tools.json"), "utf8"));
const client = new OAuth2Client();
client.setCredentials({ access_token: config.tokens.access_token });
const projectId = "curriculoautomatico-a15fa";
process.env.FIREBASE_PROJECT_ID = projectId;
const store = firestoreStore(new Firestore({ projectId, ignoreUndefinedProperties: true, auth: new GoogleAuth({ authClient: client, projectId }) }));
const [owner] = await store.select("users", { where: eq("email", email) });
if (!owner) throw new Error("Conta não encontrada");
const [row] = await store.select("workspaces", { where: and(eq("userId", owner.id), eq("demo", false)) });
const w: any = row.data;
const day = (s?: string | null) => (s || "").slice(0, 10);
console.log("ROTINA", JSON.stringify({ enabled: w.routine.enabled, mode: w.routine.mode, dailyLimit: w.routine.dailyLimit, time: w.routine.time, nextRun: w.routine.nextRun, lastRun: w.routine.lastRun, destinationPolicy: w.routine.destinationPolicy }));
console.log("FILTROS", JSON.stringify({ titles: w.filters.titles, modalities: w.filters.modalities, locations: w.filters.locations, contracts: w.filters.contracts, ageDays: w.filters.ageDays, salaryMin: w.filters.salaryMin }));
console.log("PERFIL", JSON.stringify({ confirmed: w.profile.confirmed, level: w.profile.level, skills: w.profile.skills?.length, headline: w.profile.headline }));
const apps = w.applications || [];
const byStatus: Record<string, number> = {};
for (const a of apps) byStatus[a.status] = (byStatus[a.status] || 0) + 1;
console.log("CANDIDATURAS", apps.length, JSON.stringify(byStatus));
const sent = apps.filter((a: any) => /enviad/i.test(a.status)).map((a: any) => day(a.sentAt || a.updatedAt || a.createdAt)).sort();
console.log("ÚLTIMOS ENVIOS", sent.slice(-5));
const recent = [...apps].sort((a: any, b: any) => String(b.updatedAt || b.createdAt).localeCompare(String(a.updatedAt || a.createdAt))).slice(0, 8);
for (const a of recent) console.log("  recente:", day(a.updatedAt || a.createdAt), a.status, "|", (a.blocker || a.lastError || a.message || "").toString().slice(0, 140));
const jobs = (w.jobs || []).filter((j: any) => !j.discarded && j.availability !== "closed");
const objective = jobs.filter((j: any) => matchesObjectiveFilters(j, w.profile, w.filters));
const sites = objective.filter((j: any) => matchesSelectedSites(j, w));
const free = sites.filter((j: any) => analyze(j, w.profile, w.filters).blockers.length === 0);
console.log("VAGAS ativas", jobs.length, "| passam filtros", objective.length, "| sites escolhidos", sites.length, "| sem bloqueio", free.length);
const newest = jobs.map((j: any) => day(j.discoveredAt)).sort().slice(-3);
console.log("VAGAS descobertas mais recentes", newest);
const runs = (w.runs || []).slice(0, 6).map((r: any) => `${day(r.startedAt || r.at)} ${r.origin || ""} ${r.status} ${(r.message || r.summary || "").toString().slice(0, 100)}`);
console.log("EXECUÇÕES", runs);
const notices = (w.notices || []).slice(0, 6).map((n: any) => `${day(n.at)} ${n.title}: ${String(n.message).slice(0, 120)}`);
console.log("AVISOS", notices);

console.log("FONTES");
for (const s of w.sources || []) console.log("  ", s.enabled ? "ON " : "off", s.board, "|", s.company, "|", s.discovery ? "busca" : "", s.application ? "envio" : "", "|", String(s.status || "").slice(0, 90), "|", String(s.lastError || "").slice(0, 120));
const last = (w.runs || [])[0];
console.log("ÚLTIMA EXECUÇÃO", JSON.stringify({ errors: last?.errors, sources: last?.sources, productivity: last?.productivity }).slice(0, 2500));
